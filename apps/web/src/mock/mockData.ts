export function computeMockDashboard(
  store: MockStore,
  tenantId: DevTenantId
): DashboardSummary {
  const docs = store.documents[tenantId] || [];
  const reqs = store.signRequests[tenantId] || [];
  const sigs = store.signatures[tenantId] || [];
  const dels = store.deliveries[tenantId] || [];
  const auds = store.auditEvents[tenantId] || [];

  const signRequestsByStatus: Record<string, number> = {
    PENDING_APPROVAL: 0,
    APPROVED: 0,
    SIGNING: 0,
    EVIDENCE_PENDING: 0,
    COMPLETED: 0,
    EXPIRED: 0,
    REJECTED: 0,
    FAILED: 0,
    RECONCILIATION_REQUIRED: 0,
  };
  reqs.forEach((r) => {
    signRequestsByStatus[r.status] = (signRequestsByStatus[r.status] || 0) + 1;
  });

  const deliveriesByStatus: Record<string, number> = {
    QUEUED: 0,
    SENDING: 0,
    ACKED: 0,
    RETRY_WAIT: 0,
    DEAD_LETTER: 0,
  };
  dels.forEach((d) => {
    deliveriesByStatus[d.status] = (deliveriesByStatus[d.status] || 0) + 1;
  });

  let documentVersions = 0;
  docs.forEach((d) => {
    documentVersions += d.versions.length;
  });

  return {
    tenantId,
    generatedAt: new Date().toISOString(),
    signatureMode: 'MOCK_NOT_VALID_FOR_CLINICAL_USE',
    persistence: 'IN_MEMORY',
    documents: docs.length,
    documentVersions,
    signRequestsByStatus,
    signatures: sigs.length,
    deliveriesByStatus,
    auditEvents: auds.length,
  };
}

