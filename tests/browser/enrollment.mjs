import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../../', import.meta.url));
const browser = await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1050}});
page.setDefaultTimeout(20000);
const checks=[], errors=[];
page.on('pageerror',e=>errors.push(e.message));
async function screenshot(name){await page.screenshot({path:root+'work/signup-'+name+'.png',fullPage:true});}
async function fill(key,value){await page.locator('#signup-'+key).fill(value);}
async function phoneVerify(phone){
  await fill('phone',phone);
  await page.getByRole('button',{name:'인증번호 요청',exact:true}).click();
  const otp=await page.getByTestId('dev-otp').innerText();
  assert.match(otp,/^\d{6}$/);
  await fill('otp',otp);
  await page.getByRole('button',{name:'인증번호 확인',exact:true}).click();
  await page.getByText('테스트 번호 확인 완료 · 실제 휴대폰 본인인증이 아닙니다.',{exact:true}).waitFor();
}
try{
  const stamp=Date.now().toString();
  const suffix=String(Math.floor(Math.random()*89999990)+10000000);
  await page.goto('http://127.0.0.1:5173/#/signup');
  await page.getByRole('heading',{name:'어떤 유형으로 가입하시나요?'}).waitFor();
  await screenshot('type');
  await page.getByRole('button',{name:/동의 항목 확인하기/}).click();
  assert.equal(await page.getByRole('button',{name:/동의하고 정보 입력/}).isDisabled(),true);
  await page.getByText('전자인증 서비스 가입 동의 내용 보기',{exact:true}).click();
  await screenshot('consent');
  await page.getByRole('checkbox',{name:'필수 항목 전체 동의'}).check();
  await page.getByRole('button',{name:/동의하고 정보 입력/}).click();
  assert.equal(await page.locator('#signup-licenseNumber').count(),0);
  await fill('username','personal.'+stamp);
  await fill('password','Synthetic test password 2026!');
  await fill('confirmPassword','Synthetic test password 2026!');
  await fill('name','개인시험');
  assert.equal(await page.getByRole('button',{name:'개인 가입 신청',exact:true}).isDisabled(),true);
  checks.push('Consent and phone verification required; personal form excludes clinician fields');
  await screenshot('personal');
  await phoneVerify('010'+suffix);
  assert.equal(await page.getByRole('button',{name:'개인 가입 신청',exact:true}).isEnabled(),true);
  await fill('phone','010'+String(Number(suffix)+1));
  assert.equal(await page.getByRole('button',{name:'개인 가입 신청',exact:true}).isDisabled(),true);
  checks.push('Changing the verified phone invalidates client proof');
  await phoneVerify('010'+String(Number(suffix)+1));
  await fill('confirmPassword','A mismatched password');
  await page.getByRole('button',{name:'개인 가입 신청',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'비밀번호와 비밀번호 확인이 일치하지 않습니다.'}).waitFor();
  checks.push('Password confirmation mismatch blocks signup');
  await fill('confirmPassword','Synthetic test password 2026!');
  await page.getByRole('button',{name:'개인 가입 신청',exact:true}).click();
  await page.getByRole('heading',{name:'개인 가입 신청을 완료했습니다'}).waitFor();
  assert.equal(await page.locator('input[type=password]').count(),0);
  await screenshot('personal-complete');
  checks.push('Personal registration completes against real dev backend and clears credential fields');
  await page.reload();
  await page.getByRole('radio',{name:/의료인/}).check();
  await page.getByRole('button',{name:/동의 항목 확인하기/}).click();
  await page.getByRole('checkbox',{name:'필수 항목 전체 동의'}).check();
  await page.getByRole('button',{name:/동의하고 정보 입력/}).click();
  await fill('username','doctor.'+stamp);
  await fill('password','Synthetic clinician password!');
  await fill('confirmPassword','Synthetic clinician password!');
  await fill('name','판독시험');
  await fill('institution','가상시험의료원');
  await fill('licenseNumber','000000');
  await fill('specialty','영상의학과');
  await screenshot('clinician');
  await page.setViewportSize({width:390,height:844});
  const size=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
  assert.ok(size.scroll<=size.width+1,JSON.stringify(size));
  await screenshot('mobile');
  checks.push('Clinician fields visible and mobile page has no overflow');
  await phoneVerify('010'+String(Number(suffix)+2));
  await page.getByRole('button',{name:'의료인 가입 신청',exact:true}).click();
  await page.getByRole('heading',{name:'의료인 가입 신청을 접수했습니다'}).waitFor();
  await page.getByText('의료인 자격 확인 대기',{exact:true}).waitFor();
  await screenshot('clinician-complete');
  checks.push('Clinician signup remains pending review; mock verification clearly labelled');
  assert.deepEqual(errors,[]);
  checks.push('No browser runtime errors');
  await writeFile(root+'work/signup-browser-result.json',JSON.stringify({result:'PASS',checks},null,2));
  console.log(JSON.stringify({result:'PASS',checks},null,2));
}catch(error){
  console.error(error.message);
  await screenshot('failure');
  throw error;
}finally{await browser.close();}